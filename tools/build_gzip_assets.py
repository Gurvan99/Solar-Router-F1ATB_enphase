"""Build tool: compresses static JS assets in web_assets/*.js with gzip and
generates PROGMEM C headers under web_assets/generated. The settings and raw
data scripts also get light variants with source-specific sections removed.

Usage (run manually before compiling in Arduino IDE, whenever a file under
web_assets/ is edited):

    python tools/build_gzip_assets.py

This is a build-time-only tool (no Python/pip dependency needed on the ESP32
itself, nothing here runs on the device). It requires only the Python
standard library.

Each generated header defines `<NAME>_gz` and `<NAME>_gz_len`. Sources can mark
sections with LIGHT_EXCLUDE markers (omitted from light) or LIGHT_ONLY markers
(included only in light). Each firmware variant includes only its corresponding
assets.
"""
import gzip
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "web_assets"
OUT_DIR = SRC_DIR / "generated"

# List of asset names (web_assets/<NAME>.js -> web_assets/generated/<NAME>_gz.h)
ASSETS = [
    "MainJS2",
    "MainJS3",
    "ActionsJS1",
    "ActionsJS2",
    "ActionsJS3",
    "ActionsJS4",
    "ParaJS1",
    "ParaJS2",
    "PageBruteJS1",
    "PageBruteJS2",
    "ParaCommunJS",
    "CommunCouleurJS",
]

LIGHT_ASSETS = [
    "ParaJS1",
    "ParaJS2",
    "PageBruteJS1",
    "PageBruteJS2",
]
LIGHT_EXCLUDE_BEGIN = "// LIGHT_EXCLUDE_BEGIN"
LIGHT_EXCLUDE_END = "// LIGHT_EXCLUDE_END"
LIGHT_ONLY_BEGIN = "// LIGHT_ONLY_BEGIN"
LIGHT_ONLY_END = "// LIGHT_ONLY_END"

HEADER_TEMPLATE = """// Auto-generated by tools/build_gzip_assets.py from web_assets/{source_name}.js{variant_comment}
// DO NOT EDIT BY HAND. Edit the .js source and re-run the build script.
// Source size: {raw_len} bytes, gzip size: {gz_len} bytes ({ratio:.0f}% reduction)
#pragma once
#include <pgmspace.h>

const size_t {name}_gz_len = {gz_len}UL;
const uint8_t {name}_gz[] PROGMEM = {{
{bytes_block}
}};
"""


def format_bytes(data: bytes, per_line: int = 20) -> str:
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    return "\n".join(lines)


def select_variant(source: str, name: str, light: bool) -> str:
    """Select full/light JavaScript sections marked with build-variant comments."""
    lines = []
    section = None
    for line_number, line in enumerate(source.splitlines(keepends=True), start=1):
        marker = line.strip()
        if marker in (LIGHT_EXCLUDE_BEGIN, LIGHT_ONLY_BEGIN):
            if section is not None:
                raise ValueError(f"Nested variant section in {name}.js:{line_number}")
            section = "exclude" if marker == LIGHT_EXCLUDE_BEGIN else "light_only"
        elif marker in (LIGHT_EXCLUDE_END, LIGHT_ONLY_END):
            expected = "exclude" if marker == LIGHT_EXCLUDE_END else "light_only"
            if section != expected:
                raise ValueError(f"Unmatched variant section end in {name}.js:{line_number}")
            section = None
        elif (section != "exclude" if light else section != "light_only"):
            lines.append(line)
    if section is not None:
        raise ValueError(f"Unclosed variant section in {name}.js")
    return "".join(lines)


def write_header(
    source_name: str, raw: bytes, out_name: str, variant: str, symbol_name: str
) -> None:
    compressed = gzip.compress(raw, compresslevel=9, mtime=0)
    out_path = OUT_DIR / f"{out_name}_gz.h"
    out_path.write_text(
        HEADER_TEMPLATE.format(
            source_name=source_name,
            variant_comment=" (light variant)" if variant == "light" else "",
            name=symbol_name,
            raw_len=len(raw),
            gz_len=len(compressed),
            ratio=100 * (1 - len(compressed) / max(len(raw), 1)),
            bytes_block=format_bytes(compressed),
        ),
        encoding="utf-8",
        newline="\n",
    )
    print(f"{out_name}: {len(raw)} -> {len(compressed)} bytes ({out_path.relative_to(ROOT)})")


def main() -> int:
    if not SRC_DIR.is_dir():
        print(f"Missing source folder: {SRC_DIR}", file=sys.stderr)
        return 1
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    for name in ASSETS:
        src_path = SRC_DIR / f"{name}.js"
        if not src_path.is_file():
            print(f"WARNING: missing source file {src_path}, skipped", file=sys.stderr)
            continue
        source = src_path.read_bytes().decode("utf-8")
        full_raw = select_variant(source, name, light=False).encode("utf-8")
        write_header(name, full_raw, name, "full", name)
        if name in LIGHT_ASSETS:
            light_raw = select_variant(source, name, light=True).encode("utf-8")
            write_header(name, light_raw, f"{name}_light", "light", name)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
