"""Build tool: compresses the static JS assets in web_assets/*.js with gzip and
generates C headers (web_assets/generated/<name>_gz.h) containing PROGMEM byte
arrays, so the ESP32 web server can serve them pre-compressed
(Content-Encoding: gzip) instead of embedding and streaming the raw text.

Usage (run manually before compiling in Arduino IDE, whenever a file under
web_assets/ is edited):

    python tools/build_gzip_assets.py

This is a build-time-only tool (no Python/pip dependency needed on the ESP32
itself, nothing here runs on the device). It requires only the Python
standard library.

Each generated header defines two symbols, `<NAME>_gz` (const uint8_t[]
PROGMEM) and `<NAME>_gz_len` (size_t), which are included from the existing
Page*.h/JS_*.h files and served directly with a `Content-Encoding: gzip`
header (see Server.ino).
"""
import gzip
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "web_assets"
OUT_DIR = SRC_DIR / "generated"

# List of asset names (web_assets/<NAME>.js -> web_assets/generated/<NAME>_gz.h)
ASSETS = [
    "MainJS2",
    "MainJS3",
    "ActionsJS1",
    "ActionsJS2",
    "ActionsJS3",
    "ActionsJS4",
    "ParaJS1",
    "ParaJS2",
    "PageBruteJS1",
    "PageBruteJS2",
    "ParaCommunJS",
    "CommunCouleurJS",
]

HEADER_TEMPLATE = """// Auto-generated by tools/build_gzip_assets.py from web_assets/{name}.js
// DO NOT EDIT BY HAND. Edit the .js source and re-run the build script.
// Source size: {raw_len} bytes, gzip size: {gz_len} bytes ({ratio:.0f}% reduction)
#pragma once
#include <pgmspace.h>

const size_t {name}_gz_len = {gz_len}UL;
const uint8_t {name}_gz[] PROGMEM = {{
{bytes_block}
}};
"""


def format_bytes(data: bytes, per_line: int = 20) -> str:
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    return "\n".join(lines)


def main() -> int:
    if not SRC_DIR.is_dir():
        print(f"Missing source folder: {SRC_DIR}", file=sys.stderr)
        return 1
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    for name in ASSETS:
        src_path = SRC_DIR / f"{name}.js"
        if not src_path.is_file():
            print(f"WARNING: missing source file {src_path}, skipped", file=sys.stderr)
            continue
        raw = src_path.read_bytes()
        # mtime=0 for reproducible output (no timestamp diffs on every rebuild)
        compressed = gzip.compress(raw, compresslevel=9, mtime=0)
        out_path = OUT_DIR / f"{name}_gz.h"
        out_path.write_text(
            HEADER_TEMPLATE.format(
                name=name,
                raw_len=len(raw),
                gz_len=len(compressed),
                ratio=100 * (1 - len(compressed) / max(len(raw), 1)),
                bytes_block=format_bytes(compressed),
            ),
            encoding="utf-8",
            newline="\n",
        )
        print(f"{name}: {len(raw)} -> {len(compressed)} bytes ({out_path.relative_to(ROOT)})")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
